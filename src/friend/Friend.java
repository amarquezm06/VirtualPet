package friend;

public class Friend {
    // Atributs
    public int age;
    public double averageGrade;
    public char gender; // 'H', 'D' o 'A'

    public Friend() {}

    public Friend(int age, double averageGrade, char gender) {
        this.age = age;
        this.averageGrade = averageGrade;
        this.gender = gender;
    }
}